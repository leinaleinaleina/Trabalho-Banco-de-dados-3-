package app.main.model.casestudy;

public class TipoDeclaracao {
    public int idTipoDeclaracao;
    public String tipoDeclaracao;
    public String numeroReciboAnterior;

    public int getIdTipoDeclaracao() {
        return idTipoDeclaracao;
    }
    public void setIdTipoDeclaracao(int idTipoDeclaracao) {
        this.idTipoDeclaracao = idTipoDeclaracao;
    }
    public String getTipoDeclaracao() {
        return tipoDeclaracao;
    }
    public void setTipoDeclaracao(String tipoDeclaracao) {
        this.tipoDeclaracao = tipoDeclaracao;
    }
    public String getNumeroReciboAnterior() {
        return numeroReciboAnterior;
    }
    public void setNumeroReciboAnterior(String numeroReciboAnterior) {
        this.numeroReciboAnterior = numeroReciboAnterior;
    }
}
